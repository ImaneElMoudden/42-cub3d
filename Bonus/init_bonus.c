#include "cub3d_bonus.h"

void	*ft_memset(void *s, int c, size_t n)
{
	unsigned char	*p;
	size_t			i;

	p = (unsigned char *)s;
	i = 0;
	while (i < n)
	{
		p[i] = (unsigned char)c;
		i++;
	}
	return (s);
}

void	init(void)
{
	t_game	*game;

	game = game_data();
	game->input.floor_color = -1;
	game->input.ceiling_color = -1;
}

t_game	*game_data(void)
{
	static t_game	game;

	return (&game);
}
